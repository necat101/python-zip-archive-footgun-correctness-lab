# --- Misc caveats ---------------------------------------------------------

# C28 unsupported compression method
# Create a normal zip then patch compression method to 99
buf = io.BytesIO()
with zipfile.ZipFile(buf, "w") as zf:
    zf.writestr("x.txt", b"hi")
ab = bytearray(buf.getvalue())
# Find local file header signature 0x04034b50, compression method is 2 bytes at offset 8
try:
    sig = b"\x50\x4b\x03\x04"
    idx = ab.find(sig)
    if idx >= 0:
        # compression method at idx+8
        ab[idx+8] = 99
        ab[idx+9] = 0
except Exception:
    pass
ab = bytes(ab)
ap = write_zip_raw("c28_unsupported_comp", ab)
# Note: Python zipfile still reads this fine in practice – patching only LFH not CDH
add_case("c28_unsupported_comp", "compression", ab, ap, ["x.txt"], 1, 2,
         expected_crc_ok=True,
         case_tags=["compression"],
         notes="patched compression method = 99 in LFH only – zipfile still reads OK, CDH has correct method")

