os.makedirs(ARCHIVES_DIR, exist_ok=True)

cases = []


def write_zip(case_id, members, **meta):
    """members: list of (name, bytes, compress_type)"""
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as zf:
        for name, data, ctype in members:
            zinfo = zipfile.ZipInfo(name)
            zinfo.compress_type = ctype
            zf.writestr(zinfo, data)
    archive_bytes = buf.getvalue()
    path = os.path.join(ARCHIVES_DIR, f"{case_id}.zip")
    with open(path, "wb") as f:
        f.write(archive_bytes)
    return archive_bytes, path


def write_zip_raw(case_id, archive_bytes):
    path = os.path.join(ARCHIVES_DIR, f"{case_id}.zip")
    with open(path, "wb") as f:
        f.write(archive_bytes)
    return path


def add_case(case_id, category, archive_bytes, archive_path,
             expected_member_names, expected_file_count,
             expected_uncompressed_size,
             expected_compression_methods=None,
             expected_crc_ok=True,
             expected_duplicate_names=False,
             expected_unsafe_path=False,
             expected_compression_ratio_guard=False,
             expected_safe_extract=True,
             case_tags=None,
             safe_to_extract_in_tempdir=True,
             dry_run_only=False,
             malformed=False,
             notes=""):
    cases.append({
        "case_id": case_id,
        "category": category,
        "archive_path": archive_path,
        "archive_byte_length": len(archive_bytes),
        "expected_member_names": expected_member_names,
        "expected_file_count": expected_file_count,
        "expected_uncompressed_size": expected_uncompressed_size,
        "expected_compression_methods": expected_compression_methods or [],
        "expected_crc_ok": expected_crc_ok,
        "expected_duplicate_names": expected_duplicate_names,
        "expected_unsafe_path": expected_unsafe_path,
        "expected_compression_ratio_guard": expected_compression_ratio_guard,
        "expected_safe_extract": expected_safe_extract,
        "case_tags": case_tags or [category],
        "safe_to_extract_in_tempdir": safe_to_extract_in_tempdir,
        "dry_run_only": dry_run_only,
        "malformed": malformed,
        "notes": notes,
    })


